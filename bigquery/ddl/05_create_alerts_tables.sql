-- Create AML/Fraud Alerts Tables

-- AML Alerts Table
CREATE TABLE IF NOT EXISTS `your-project-id.fincrime_er.aml_alerts` (
  alert_id STRING NOT NULL,
  alert_type STRING NOT NULL,
  severity STRING NOT NULL,
  golden_entity_id STRING NOT NULL,
  alert_date DATE NOT NULL,
  alert_timestamp TIMESTAMP NOT NULL,
  description STRING,
  transaction_count INT64,
  total_amount NUMERIC,
  time_window_start TIMESTAMP,
  time_window_end TIMESTAMP,
  time_window_hours FLOAT64,
  transaction_ids ARRAY<STRING>,
  alert_details JSON,
  status STRING DEFAULT 'OPEN',
  assigned_to STRING,
  batch_id STRING,
  detection_rule STRING,
  risk_score FLOAT64
)
PARTITION BY alert_date
CLUSTER BY golden_entity_id, alert_type, severity
OPTIONS(
  description="AML and Fraud alerts generated by detection engine",
  labels=[("layer", "alerts"), ("domain", "fincrime")]
);

-- Alert Investigations Table
CREATE TABLE IF NOT EXISTS `your-project-id.fincrime_er.alert_investigations` (
  investigation_id STRING NOT NULL,
  alert_id STRING NOT NULL,
  golden_entity_id STRING NOT NULL,
  investigator STRING,
  status STRING,
  priority STRING,
  assigned_date TIMESTAMP,
  investigation_notes STRING,
  sar_filed BOOLEAN DEFAULT FALSE,
  sar_filing_date DATE,
  sar_reference STRING,
  resolution_date TIMESTAMP,
  resolution_reason STRING,
  actions_taken STRING,
  created_timestamp TIMESTAMP,
  updated_timestamp TIMESTAMP
)
CLUSTER BY alert_id, golden_entity_id
OPTIONS(
  description="Investigation tracking for AML alerts",
  labels=[("layer", "alerts"), ("domain", "fincrime")]
);

-- Alert Summary View
CREATE OR REPLACE VIEW `your-project-id.fincrime_er.vw_alert_summary` AS
SELECT 
  alert_date,
  alert_type,
  severity,
  COUNT(*) as alert_count,
  COUNT(DISTINCT golden_entity_id) as entities_flagged,
  SUM(total_amount) as total_amount_flagged
FROM `your-project-id.fincrime_er.aml_alerts`
GROUP BY alert_date, alert_type, severity
ORDER BY alert_date DESC, severity DESC;
